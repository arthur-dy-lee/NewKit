"""Generate the smallest valid OOXML blanks: blank.xlsx / blank.docx / blank.pptx.

These files are bundled into the NewKit app and copied as-is when the user creates
a new Excel/Word/PowerPoint document. They open cleanly in Microsoft Office and
Apple's iWork suite (which uses Office formats for import).
"""

from __future__ import annotations
import os
import zipfile

OUT_DIR = os.path.join(os.path.dirname(__file__), "..", "Sources", "App", "Resources", "OfficeTemplates")
os.makedirs(OUT_DIR, exist_ok=True)


def write_zip(path: str, files: dict[str, str]) -> None:
    if os.path.exists(path):
        os.remove(path)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for name, content in files.items():
            z.writestr(name, content)
    print(f"wrote {path}")


